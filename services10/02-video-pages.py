#!/usr/bin/env python3
"""Publish a Watch page for every archived public YouTube upload/Short/live ID.

Video ingestion is independent of Community posts. Each valid video is
classified, retained by stable YouTube ID, and presented in the corresponding
category of /watch/. Older Watch pages are refreshed only when generated by
this script; editorial hand-written pages are never replaced.
"""
from __future__ import annotations
import html
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
VIDEO_ID=re.compile(r"^[A-Za-z0-9_-]{11}$")
FALLBACK="/assets/zt-editorial-fallback.svg"
LABELS={"recensioni":"Recensioni","speciali":"Speciali","extra":"Extra",
        "tech-impact":"Tech Impact","gaming-inside":"Gaming Inside",
        "unboxing":"Unboxing","gaming":"News Gaming / Gameplay",
        "tech":"News Tech","video":"Altri video"}

def load_list(path:Path)->list[dict]:
    try:
        data=json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data,list) else []
    except (ValueError,OSError):
        return []

def video_category(title:str)->str:
    """Use explicit editorial keywords, falling back to a general Video group."""
    name=str(title or "").casefold()
    if re.search(r"\b(news[\s:]+speciali|speciale|speciali)\b",name):return "speciali"
    if re.search(r"\b(news[\s:]+extra)\b",name):return "extra"
    if "tech impact" in name:return "tech-impact"
    if "gaming inside" in name or "gaming insight" in name:return "gaming-inside"
    if re.search(r"\b(recensione|review)\b",name):return "recensioni"
    if "unboxing" in name:return "unboxing"
    if "news gaming" in name:return "gaming"
    if "news tech" in name:return "tech"
    if re.search(r"\b(gameplay|playstation|ps5|xbox|nintendo)\b",name):return "gaming"
    if re.search(r"\b(smartphone|notebook|tablet|router|smartwatch)\b",name):return "tech"
    return "video"

def sync_video_catalog(root:Path=ROOT)->dict:
    imported=load_list(root/"services10-data/videos.json")
    original=load_list(root/"home-video-feed.json")
    entries={str(x["id"]):x for x in original if isinstance(x,dict)
             and VIDEO_ID.fullmatch(str(x.get("id") or ""))}
    initial=set(entries)
    for video in imported:
        if not isinstance(video,dict):continue
        vid=str(video.get("id") or "")
        if not VIDEO_ID.fullmatch(vid):continue
        previous=entries.get(vid,{})
        name=str(video.get("title") or previous.get("title") or "Video ZazoomTek")
        entries[vid]={**previous,"id":vid,"title":name,
                      "publishedAt":str(video.get("published") or previous.get("publishedAt") or ""),
                      "category":video_category(name),
                      "short":bool(video.get("short",previous.get("short",False))),
                      "live":video.get("live") in ("live","upcoming"),
                      "embeddable":bool(video.get("embeddable",previous.get("embeddable",True))),
                      "completedLive":False}
    # Previously imported records also receive editorial category labels.
    for video in entries.values():
        video["category"]=video_category(str(video.get("title") or ""))
    catalog=sorted(entries.values(),key=lambda x:str(x.get("publishedAt") or ""),reverse=True)
    feed_path=root/"home-video-feed.json"
    if catalog!=original:
        feed_path.write_text(json.dumps(catalog,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")

    folder=root/"watch"
    folder.mkdir(parents=True,exist_ok=True)
    written=0
    for video in catalog:
        vid=video["id"]
        target=folder/(vid+".html")
        if target.is_file() and "<!-- SERVICES10_GENERATED -->" not in target.read_text(encoding="utf-8",errors="replace"):
            continue
        title=html.escape(str(video.get("title") or "Video ZazoomTek"))
        cat=html.escape(str(video.get("category") or "video"),quote=True)
        thumb="https://i.ytimg.com/vi/"+vid+"/hqdefault.jpg"
        if video.get("embeddable",True):
            player=('<iframe title="'+title+'" loading="lazy" allowfullscreen '
                    'referrerpolicy="strict-origin-when-cross-origin" '
                    'src="https://www.youtube-nocookie.com/embed/'+vid+'"></iframe>')
        else:
            player=('<img class="zt-watch-thumbnail" src="'+thumb+
                    '" onerror="this.onerror=null;this.src=\''+FALLBACK+
                    '\'" alt="'+title+'">')
        date=html.escape(str(video.get("publishedAt") or ""),quote=True)
        body=(
            '<!-- SERVICES10_GENERATED -->\n<!doctype html><html lang="it"><head>'
            '<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            '<title>'+title+' | ZazoomTek</title>'
            '<link rel="stylesheet" href="/zt-design.css">'
            '<link rel="canonical" href="https://zazoomtek.it/watch/'+vid+'.html">'
            '<meta property="og:image" content="'+thumb+'">'
            '<meta property="article:published_time" content="'+date+'">'
            '<style>body{background:#eee;font:16px Arial}.zt-watch-article{max-width:100%;'
            'min-width:0;background:#fff;padding:25px}iframe{width:100%;aspect-ratio:16/9;border:0}'
            '.zt-watch-thumbnail{display:block;width:100%;max-width:900px;aspect-ratio:16/9;object-fit:cover}'
            '</style></head><body><header><a href="/">ZazoomTek</a></header>'
            '<main class="zt-watch-page"><article class="zt-watch-article" data-post-category="'+cat+'">'
            '<h1>'+title+'</h1>'+player
            +'<p><a href="https://www.youtube.com/watch?v='+vid+'" rel="noopener">'
            'Guarda il video su YouTube</a></p></article></main>'
            '<script src="/studio/edit-button.js" defer></script></body></html>'
        )
        if not target.is_file() or target.read_text(encoding="utf-8")!=body:
            target.write_text(body,encoding="utf-8")
            written+=1

    listing=folder/"index.html"
    if not listing.is_file() or "<!-- SERVICES10_GENERATED -->" in listing.read_text(encoding="utf-8",errors="replace"):
        grouped=defaultdict(list)
        for video in catalog:grouped[video.get("category") or "video"].append(video)
        sections=[]
        for category,label in LABELS.items():
            group=grouped.get(category,[])
            if not group:continue
            cards=[]
            for video in group:
                vid=video["id"]
                title=html.escape(str(video.get("title") or "Video ZazoomTek"))
                cards.append('<article class="zt-watch-card" data-post-category="'+category+'">'
                             '<a href="/watch/'+vid+'.html"><img loading="lazy" '
                             'src="https://i.ytimg.com/vi/'+vid+'/hqdefault.jpg" '
                             'onerror="this.onerror=null;this.src=\''+FALLBACK+'\'" alt="'+title+'">'
                             '<h2>'+title+'</h2></a></article>')
            sections.append('<section><h2>'+html.escape(label)+'</h2>'+"".join(cards)+'</section>')
        doc=('<!-- SERVICES10_GENERATED -->\n<!doctype html><html lang="it">'
             '<head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
             '<title>Video, Recensioni e Speciali ZazoomTek</title>'
             '<link rel="stylesheet" href="/zt-design.css"></head>'
             '<body><main><h1>Video e Shorts ZazoomTek</h1>'+"".join(sections)+'</main></body></html>')
        if not listing.is_file() or listing.read_text(encoding="utf-8")!=doc:
            listing.write_text(doc,encoding="utf-8")
    print("Public YouTube archive:",len(catalog),"total Watch records,",
          len(set(entries)-initial),"new videos,",written,"generated/updated Watch pages")
    return {"new_videos":len(set(entries)-initial),"watch_pages":written,"total":len(catalog)}

if __name__=="__main__":
    sync_video_catalog()
